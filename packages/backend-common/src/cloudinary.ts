import crypto from "crypto";

// ─── Cloudinary signed direct-upload helper ──────────────────
// Generating an upload signature is purely cryptographic: sort the
// upload parameters alphabetically, join them as key=value&…, append
// the API secret, and SHA-1 the result (Cloudinary signing spec).
// No network hop is required — which is exactly why utils-service no
// longer needs to be in the loop: each owning service signs locally
// (<1ms, no Axios, no Lambda) and hands the payload to its client,
// which uploads the bytes straight to Cloudinary's REST endpoint.
//
// SECURITY CONTRACT:
//   - CLOUDINARY_API_SECRET stays server-side only. It is never
//     returned, logged, or embedded in anything sent to a client.
//   - Clients receive only { signature, timestamp, apiKey, cloudName }
//     plus the signed public parameters — enough to POST the file
//     directly to https://api.cloudinary.com/v1_1/<cloud>/image/upload.
//   - The signature is valid ONLY for the exact parameter set signed
//     here (folder/publicId/tags/transformation), so a client cannot
//     escalate to other folders or overwrite arbitrary assets.

export interface CloudinarySignatureOptions {
  /** Destination folder, e.g. "foodo/menu" — REQUIRED, keeps buckets organized */
  folder: string;
  /** Optional explicit public_id (without folder); generated by Cloudinary when omitted */
  publicId?: string;
  /** Optional tags to attach to the uploaded asset */
  tags?: string[];
  /** Optional chained transformation string, e.g. "w_1200,h_1200,c_limit,q_auto" */
  transformation?: string;
  /**
   * Escape hatch for any other Cloudinary upload param (context, eager, etc.).
   * Values are stringified; booleans become the bare "true"/"false" the API expects.
   */
  extraParams?: Record<string, string | number | boolean>;
  /** Override the timestamp (unix seconds); defaults to now — exposed for testing */
  timestamp?: number;
}

export interface CloudinaryUploadSignature {
  /** HMAC/SHA-1 hex signature over the sorted params — valid for ~1h (Cloudinary default) */
  signature: string;
  /** Unix seconds — clients must send this back verbatim */
  timestamp: number;
  /** Public API key — safe to expose */
  apiKey: string;
  /** Cloud name — safe to expose */
  cloudName: string;
  /** The signed params, echoed back so the client can replay them verbatim */
  folder: string;
  publicId?: string;
  tags?: string[];
  transformation?: string;
  [key: string]: unknown;
}

// The subset of params Cloudinary includes in the signature computation,
// after serialization to their wire format (tags joined with commas, etc.)
type SignableParams = Record<string, string>;

function resolveCredentials(): { cloudName: string; apiKey: string; apiSecret: string } {
  const cloudName = process.env.CLOUDINARY_CLOUD_NAME;
  const apiKey = process.env.CLOUDINARY_API_KEY;
  const apiSecret = process.env.CLOUDINARY_API_SECRET;

  if (!cloudName || !apiKey || !apiSecret) {
    throw new Error(
      "Cloudinary credentials missing: set CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY and CLOUDINARY_API_SECRET",
    );
  }

  return { cloudName, apiKey, apiSecret };
}

// ─── Core: Cloudinary's signature algorithm, by the book ─────
// 1. Drop empty values and the reserved `api_key`/`file`/`resource_type`/`cloud_name` params
// 2. Serialize remaining values (arrays → comma-joined)
// 3. Sort keys alphabetically (ASCII/byte order — locale-independent sort!)
// 4. Join as "key=value" with "&"
// 5. Append the API secret, SHA-1 the whole thing, hex-encode

export function apiSignRequest(params: SignableParams, apiSecret: string): string {
  const toSign = Object.keys(params)
    .filter((key) => params[key] !== "" && params[key] !== undefined)
    .sort()
    .map((key) => `${key}=${params[key]}`)
    .join("&");

  return crypto
    .createHash("sha1")
    .update(toSign + apiSecret, "utf8")
    .digest("hex");
}

export function createCloudinaryUploadSignature(
  options: CloudinarySignatureOptions,
): CloudinaryUploadSignature {
  const { cloudName, apiKey, apiSecret } = resolveCredentials();

  const timestamp = options.timestamp ?? Math.floor(Date.now() / 1000);

  // ─── Build the wire-format param set ─────────────────────────
  const params: SignableParams = {
    timestamp: String(timestamp),
    folder: options.folder,
  };

  if (options.publicId !== undefined) {
    params.public_id = options.publicId;
  }
  if (options.tags !== undefined && options.tags.length > 0) {
    params.tags = options.tags.join(","); // Cloudinary tags wire-format
  }
  if (options.transformation !== undefined && options.transformation !== "") {
    params.transformation = options.transformation;
  }
  if (options.extraParams) {
    for (const [key, value] of Object.entries(options.extraParams)) {
      params[key] = String(value);
    }
  }

  const signature = apiSignRequest(params, apiSecret);

  // ─── Client-facing payload — never includes the secret ──────
  return {
    signature,
    timestamp,
    apiKey,
    cloudName,
    folder: options.folder,
    ...(options.publicId !== undefined ? { publicId: options.publicId } : {}),
    ...(options.tags && options.tags.length > 0 ? { tags: options.tags } : {}),
    ...(options.transformation ? { transformation: options.transformation } : {}),
  };
}
